VERSION = "ocr-v2.1-2026-09-01"


_NOTATION_RULES = """[표기 규칙 — LaTeX 백슬래시 절대 사용 금지]

기본:
- 분수: (a/b)                예: (x+1)/(x-2)
- 제곱근: √n 또는 √(...)     예: √3, √(x+1)
- 지수: x^2, 2^n              예: (x-1)^2
- 첨자: a_n, x_1              예: a_{n+1} 은 a_(n+1) 로
- 로그: log_2 72              밑은 _ 뒤에
- 곱셈: ×,  나눗셈: ÷
- 부등호: ≤, ≥, ≠
- 무한대: ∞

함수와 그래프 단원 특화:
- 합성함수: f∘g (동그라미 기호), (f∘g)(x)
- 역함수: f⁻¹ 또는 f^(-1) — 학생이 f-1로 썼어도 문맥상 역함수면 f^(-1)로 옮기고, 뺄셈이면 f-1 그대로
- 정의역/공역/치역 기호: X, Y, R, N, Z 등은 그대로
- 좌표: (a, b), 순서쌍
- 집합: {1, 2, 3}, {x | x>0}
- 대응 화살표: → (오른쪽 화살표)
- 대소 관계: f(a)=b 형태 유지"""


_SOLUTION_SPECIFIC = """[학생 풀이 OCR — 추가 원칙]

역할: 학생이 쓴 풀이를 있는 그대로 옮기는 것. 채점 근거가 되므로 정확성이 최우선.

★ 절대 금지:
- 학생의 수학적 오류를 임의로 교정하지 마세요.
  예: 학생이 "f(-2) = -5"라고 썼는데 실제는 -5가 아니어도, "-5" 그대로 옮김.
- 학생이 안 쓴 단계를 채우지 마세요.
- 학생이 지운 부분은 옮기지 마세요 (선을 그어 지운 것, 지우개로 지운 흔적).

단계 나누기:
- 하나의 "단계"는 학생이 물리적으로 줄바꿈했거나, 등식 하나가 끝나는 지점.
- 애매하면 세밀하게 나누기 (합쳐 놓으면 채점자가 어느 부분을 지적할지 모호).
- 각 단계는 짧을수록 좋음. 한 줄에 여러 등식이면 각각 다른 index로.

판독 불가 처리:
- 완전히 못 읽는 글자: [?] 로 표시
- 부분적으로 애매: 가장 그럴듯한 해석 + 뒤에 (?) 붙이기. 예: "x=3(?)"
- 지운 흔적/취소선: 그 부분 자체를 옮기지 않음
- 화살표/등호 대신 그림: "→" 또는 "="로 옮기고, 완전 이해 불가면 [그림] 표시"""


