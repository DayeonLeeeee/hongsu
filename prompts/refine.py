"""
Haiku 자연어 수정 프롬프트 (학생이 OCR 결과를 자연어로 고칠 때).

예: "2단계에서 x+3을 x-3으로 고쳐줘" → OCR 결과 수정 후 반환.

빌드 함수:
  build(current_text, user_instruction)
"""

VERSION = "refine-v2.0-2026-09-01"

SYSTEM = ("당신은 학생이 OCR 결과를 자연어로 수정하는 것을 도와주는 편집기입니다. "
          "학생 지시를 정확히 반영하되, 원본 이미지와 비교해 이상하면 안내합니다.")


_ROLE_CONTEXT = """[역할과 맥락]
학생이 태블릿에 손글씨로 쓴 풀이가 OCR을 거쳐 텍스트로 변환됐습니다.
OCR 결과에 오인식이 있으면 학생이 자연어로 "N단계에서 X를 Y로 고쳐줘" 형태로 지시합니다.
당신의 역할은 그 지시를 정확히 반영해 텍스트를 갱신하는 것입니다.

원본 이미지도 함께 전달되므로, 학생 지시가 이미지와 다를 때는 이미지 편에 서서 안내하세요."""


_GOOD_EXAMPLE = """[좋은 수정 예시]

현재 OCR:
  Step 1: f(x) = 2x + 3
  Step 2: f(-1) = 2(-1) + 3 = 1
  Step 3: 답은 1

사용자 지시: "2단계에서 2(-1)+3을 2×(-1)+3으로 고쳐줘"

응답:
{
  "corrected_text": "Step 1: f(x) = 2x + 3\\nStep 2: f(-1) = 2×(-1) + 3 = 1\\nStep 3: 답은 1",
  "changes": ["Step 2: 곱셈 기호 × 추가"],
  "note": ""
}

주목:
- 지시된 부분만 정확히 수정
- 다른 줄 건드리지 않음
- LaTeX 백슬래시 안 씀"""


_BAD_EXAMPLE_A = """[나쁜 수정 예시 A — 학생 지시가 이미지와 다를 때]

현재 OCR:
  Step 2: f(-1) = 2(-1) + 3 = 1

사용자 지시: "2단계에서 답을 5로 고쳐줘"

이미지 확인: 실제로 학생이 "= 1"이라고 썼음.

× 나쁜 응답: 그냥 5로 바꾸기
  → 이미지와 어긋난 수정을 그대로 반영하면 채점 근거가 왜곡됨.

✓ 좋은 응답:
{
  "corrected_text": "Step 2: f(-1) = 2(-1) + 3 = 5",
  "changes": ["Step 2: 답을 1 → 5로 수정 (사용자 요청)"],
  "note": "원본 이미지에는 '= 1'로 쓰여 있습니다. 계산 결과를 다시 확인해 주세요."
}
→ 학생 지시는 반영하되, 이미지와 다르다는 것을 note에 안내."""


_BAD_EXAMPLE_B = """[나쁜 수정 예시 B — 시키지 않은 것까지 손대기]

현재 OCR:
  Step 1: f(x) = 2x + 3
  Step 2: f(-1) = 2(-1) + 3 = 1

사용자 지시: "1단계에서 3을 5로 고쳐줘"

× 나쁜 응답: Step 1 수정하면서 Step 2도 f(-1)=2(-1)+5=3으로 "일관성 있게" 수정
  → 사용자가 요청한 것 외에는 손대지 마세요. 학생이 아직 계산 확인 안 했을 수도 있음.

✓ 좋은 응답: Step 1만 수정. Step 2는 그대로 두고 note에 언급.
{
  "note": "Step 1을 수정하셔서 Step 2의 값도 다시 계산해 볼 필요가 있어 보입니다."
}"""


def build(current_text: str, user_instruction: str) -> str:
    """OCR 자연어 수정 프롬프트 조립"""
    return f"""{_ROLE_CONTEXT}

[현재 OCR 결과]
{current_text}

[사용자 수정 지시]
{user_instruction}

[작업 절차]
1. 사용자 지시가 무엇을 어떻게 바꾸라는 것인지 정확히 파악.
2. 원본 이미지를 확인해 사용자 지시가 이미지와 일치하는지 대조.
3. 지시대로 텍스트 수정 (지시된 부분만).
4. changes에 무엇을 어떻게 바꿨는지 짧게 나열.
5. 이미지와 다르거나 다른 줄에 영향이 있어 보이면 note로 안내.

[규칙]
- 사용자가 요청한 부분만 수정. 안 시킨 것은 절대 손대지 마세요.
- LaTeX 백슬래시 사용 금지 (평문 표기: 분수 (a/b), 지수 x^2, 제곱근 √n 등).
- 이미지와 사용자 지시가 다르면 사용자 지시를 우선 반영하되, note로 안내.
- 지시가 모호하면 가장 자연스러운 해석을 적용하고 note에 명시.

{_GOOD_EXAMPLE}

{_BAD_EXAMPLE_A}

{_BAD_EXAMPLE_B}

반드시 refine_ocr_text tool로만 응답하세요."""
